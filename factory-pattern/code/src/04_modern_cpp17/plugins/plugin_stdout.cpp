// ===========================================================================
// 第 4 篇的"插件"翻译单元。
//
// 这个文件没有定义任何被 main 调用的函数 —— 它存在的全部目的，
// 就是在静态初始化阶段往注册表里塞一条记录。
//
// 关键点：注册句柄在**匿名命名空间**里，因此它对外部没有任何符号。
// 而静态库是按成员取用的：链接器只会为了解析某个未定义符号才把一个
// 目标文件从静态库里取出来。既然它没有任何外部符号被引用，
// 这个目标文件就不会被取出，挂在它上面的静态初始化也就不会执行。
//
// 这就是"自注册被链接器悄悄抹掉"的完整机制 ——
// 它不报错、不警告，只是安静地什么都没发生。
// ===========================================================================

#include "self_register.h"

#include "fp/logger.h"

#include <memory>

namespace {

const fp::LoggerRegistrar fp_registrar_plugin_stdout{
    "plugin-stdout",
    []() -> std::unique_ptr<fp::Logger> {
        return std::make_unique<fp::ConsoleLogger>();
    }};

}  // namespace
